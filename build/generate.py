#!/usr/bin/env python3
"""Generate adapter outputs from core/.

    python build/generate.py          # write generated files
    python build/generate.py --check  # exit 1 if committed files are out of sync

Sources (hand-edited): VERSION, core/**, adapters/<agent>/hooks/**.
Outputs (never hand-edit): everything listed in build/generated-files.txt, plus
the __version__ stamp in core/scripts/coding_plugin.py.

Adding an adapter = one gen_<agent>() function returning {path: text} and an
entry in ADAPTERS. Adapters contain wiring only; content comes from core/.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from typing import Callable, Dict, List, Tuple

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = "build/generated-files.txt"
REPO_URL = "https://github.com/arthurcyf/coding-plugin"
AUTHOR = {"name": "Arthur Chan"}
DESCRIPTION = (
    "Agent-neutral guardrails for AI coding: command and path guards, format on edit, "
    "stop-time checks, and fix-issue / feature / review / handoff / explain workflows."
)

Outputs = Dict[str, str]


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------


def read(rel: str) -> str:
    with open(os.path.join(ROOT, *rel.split("/")), encoding="utf-8") as fh:
        return fh.read().replace("\r\n", "\n")


def list_files(rel_dir: str) -> List[str]:
    """Repo-relative paths of all files under rel_dir (sorted, '/' separators)."""
    base = os.path.join(ROOT, *rel_dir.split("/"))
    found = []
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if d != "__pycache__")
        for name in sorted(filenames):
            full = os.path.join(dirpath, name)
            found.append(os.path.relpath(full, ROOT).replace("\\", "/"))
    return found


def version() -> str:
    v = read("VERSION").strip()
    if not re.fullmatch(r"\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?", v):
        raise SystemExit(f"VERSION is not semantic: {v!r}")
    return v


def to_json(obj: object) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def parse_frontmatter(text: str) -> Tuple[Dict[str, str], str]:
    """Parse flat 'key: value' frontmatter (all the core format needs)."""
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError("missing frontmatter")
    meta: Dict[str, str] = {}
    for line in m.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, sep, value = line.partition(":")
        if not sep:
            raise ValueError(f"bad frontmatter line: {line!r}")
        meta[key.strip()] = value.strip().strip('"')
    return meta, text[m.end():]


def render_frontmatter(items: List[Tuple[str, object]]) -> str:
    lines = ["---"]
    for key, value in items:
        if isinstance(value, bool):
            rendered = "true" if value else "false"
        elif key in ("description", "argument-hint"):
            rendered = json.dumps(str(value), ensure_ascii=False)  # JSON strings are valid YAML
        else:
            rendered = str(value)
        lines.append(f"{key}: {rendered}")
    lines.append("---\n")
    return "\n".join(lines)


def stamp_version(core_src: str, v: str) -> str:
    new, n = re.subn(r'^__version__ = "[^"]*"$', f'__version__ = "{v}"', core_src, count=1, flags=re.M)
    if n != 1:
        raise SystemExit("core/scripts/coding_plugin.py: __version__ line not found")
    return new


def roles() -> Dict[str, Tuple[Dict[str, str], str, str]]:
    """name -> (meta, body, source path)."""
    out = {}
    for rel in list_files("core/roles"):
        if rel.endswith(".md"):
            meta, body = parse_frontmatter(read(rel))
            out[meta["name"]] = (meta, body, rel)
    return out


def skills() -> Dict[str, Tuple[Dict[str, str], str, str]]:
    out = {}
    for rel in list_files("core/skills"):
        if rel.endswith("/SKILL.md"):
            meta, body = parse_frontmatter(read(rel))
            name = rel.split("/")[-2]
            if meta.get("name") != name:
                raise SystemExit(f"{rel}: frontmatter name must equal the folder name ({name})")
            out[name] = (meta, body, rel)
    return out


DELEGATE_RE = re.compile(r"\{\{delegate:([a-z0-9-]+)\}\}")
SKILL_DIR_RE = re.compile(r"\{\{skill_dir\}\}")


def referenced_roles(body: str) -> List[str]:
    return sorted(set(DELEGATE_RE.findall(body)))


def generated_note(src: str) -> str:
    return f"<!-- GENERATED by build/generate.py from {src}. Edit the source, then run: python build/generate.py -->\n"


# Skills that bundle the installer (core script + rules + templates) under assets/.
BUNDLES_CORE = {"init"}


def bundle_core(prefix: str, stamped_core: str) -> Outputs:
    out: Outputs = {f"{prefix}/coding_plugin.py": stamped_core}
    for rel in list_files("core/rules") + list_files("core/templates"):
        sub = rel[len("core/"):]
        out[f"{prefix}/{sub}"] = read(rel)
    return out


# ---------------------------------------------------------------------------
# adapter: Claude Code (plugin + marketplace)
# ---------------------------------------------------------------------------

CLAUDE_TOOLS = {"read": ["Read", "Grep", "Glob"], "run": ["Bash"], "edit": ["Edit", "Write"]}
CLAUDE_SKILL_EXTRAS: Dict[str, List[Tuple[str, object]]] = {
    "init": [("argument-hint", "[stack]"), ("disable-model-invocation", True)],
    "fix-issue": [("argument-hint", "<issue description, error or issue number>")],
    "feature": [("argument-hint", "<feature description>")],
    "review": [("argument-hint", "[base branch]")],
    "handoff": [],
    "explain": [("argument-hint", "<component, feature or question>")],
    "sandbox": [("argument-hint", "<task description>")],
}


def claude_tools(permissions: str) -> str:
    tools: List[str] = []
    for perm in [p.strip() for p in permissions.split(",") if p.strip()]:
        if perm not in CLAUDE_TOOLS:
            raise SystemExit(f"unknown role permission {perm!r} (use read, run, edit)")
        tools += CLAUDE_TOOLS[perm]
    return ", ".join(tools)


def claude_delegate(match: "re.Match[str]") -> str:
    role = match.group(1)
    return (
        f"Delegate this to the `coding-plugin:{role}` subagent. If subagents are unavailable, "
        f"follow `references/{role}.md` yourself."
    )


def gen_claude_code(stamped_core: str, v: str) -> Outputs:
    p = "adapters/claude-code"
    out: Outputs = {}
    out[f"{p}/lib/coding_plugin.py"] = stamped_core
    for rel in list_files("core/rules"):
        out[f"{p}/lib/rules/{os.path.basename(rel)}"] = read(rel)

    out[f"{p}/.claude-plugin/plugin.json"] = to_json({
        "name": "coding-plugin",
        "version": v,
        "description": DESCRIPTION,
        "author": AUTHOR,
        "homepage": REPO_URL,
        "repository": REPO_URL,
        "license": "MIT",
        "keywords": ["guardrails", "hooks", "code-review", "testing", "agents-md", "skills"],
    })
    out[".claude-plugin/marketplace.json"] = to_json({
        "name": "coding-plugin",
        "owner": AUTHOR,
        "description": "Marketplace for coding-plugin, agent-neutral guardrails for AI coding agents.",
        "plugins": [{
            "name": "coding-plugin",
            "source": "./adapters/claude-code",
            "description": DESCRIPTION,
            "category": "development",
        }],
    })

    all_roles = roles()
    for name, (meta, body, src) in all_roles.items():
        fm = render_frontmatter([
            ("name", name),
            ("description", meta["description"]),
            ("tools", claude_tools(meta.get("permissions", "read"))),
        ])
        out[f"{p}/agents/{name}.md"] = fm + generated_note(src) + body

    for name, (meta, body, src) in skills().items():
        sd = f"{p}/skills/{name}"
        rendered = SKILL_DIR_RE.sub("${CLAUDE_SKILL_DIR}", DELEGATE_RE.sub(claude_delegate, body))
        fm = render_frontmatter([("name", name), ("description", meta["description"])]
                                + CLAUDE_SKILL_EXTRAS.get(name, []))
        out[f"{sd}/SKILL.md"] = fm + generated_note(src) + rendered
        for role in referenced_roles(body):
            if role not in all_roles:
                raise SystemExit(f"{src}: unknown role {role!r}")
            rmeta, rbody, rsrc = all_roles[role]
            out[f"{sd}/references/{role}.md"] = generated_note(rsrc) + rbody
        for rel in list_files(f"core/skills/{name}"):
            if not rel.endswith("/SKILL.md"):
                out[f"{sd}/{rel[len(f'core/skills/{name}/'):]}"] = read(rel)
        if name in BUNDLES_CORE:
            out.update(bundle_core(f"{sd}/assets", stamped_core))
    return out


ADAPTERS: Dict[str, Callable[[str, str], Outputs]] = {
    "claude-code": gen_claude_code,
}


# ---------------------------------------------------------------------------
# driver
# ---------------------------------------------------------------------------


def build() -> Tuple[Outputs, Outputs]:
    """Returns (generated outputs, stamped sources)."""
    v = version()
    stamped_core = stamp_version(read("core/scripts/coding_plugin.py"), v)
    out: Outputs = {}
    for gen in ADAPTERS.values():
        out.update(gen(stamped_core, v))
    out[MANIFEST] = "# Files generated by build/generate.py. Do not edit them by hand.\n" + "".join(
        f"{path}\n" for path in sorted(out)
    )
    return out, {"core/scripts/coding_plugin.py": stamped_core}


def previous_manifest() -> List[str]:
    try:
        lines = read(MANIFEST).splitlines()
    except OSError:
        return []
    return [ln for ln in lines if ln and not ln.startswith("#")]


def current(path: str) -> str:
    try:
        return read(path)
    except OSError:
        return "\0missing"


def main(argv: List[str] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify only; exit 1 if anything is out of sync")
    args = ap.parse_args(argv)

    outputs, stamped = build()
    wanted = {**outputs, **stamped}
    stale = sorted(set(previous_manifest()) - set(outputs))
    changed = sorted(path for path, text in wanted.items() if current(path) != text)

    if args.check:
        problems = [f"out of date: {p}" for p in changed] + [f"stale (should be deleted): {p}" for p in stale]
        if problems:
            print("Generated files are out of sync with core/. Run: python build/generate.py")
            print("\n".join(f"  {p}" for p in problems))
            return 1
        print(f"Generated files are in sync ({len(outputs)} files).")
        return 0

    for path in changed:
        full = os.path.join(ROOT, *path.split("/"))
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(wanted[path])
    for path in stale:
        full = os.path.join(ROOT, *path.split("/"))
        if os.path.isfile(full):
            os.remove(full)
    print(f"Wrote {len(changed)} file(s), removed {len(stale)} stale file(s); {len(outputs)} generated in total.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
